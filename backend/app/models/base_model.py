from datetime import datetime, timezone

from sqlalchemy import DateTime, Integer
from sqlalchemy.orm import Mapped, mapped_column

from app.db.base import Base


# A single UTC factory keeps timestamps timezone-aware and consistent across
# every model that inherits from TimestampModel.
def utc_now() -> datetime:
    """Return the current time as a timezone-aware UTC datetime."""
    return datetime.now(timezone.utc)


class TimestampModel(Base):
    """Abstract base for models that need identity and audit timestamps."""

    # Abstract models centralize shared columns without creating their own
    # database table; concrete models inherit these fields into their tables.
    __abstract__ = True

    # A numeric primary key gives each persisted row a stable identity and is
    # automatically generated by the database when a row is inserted.
    id: Mapped[int] = mapped_column(
        Integer,
        primary_key=True,
        autoincrement=True,
    )

    # Creation and update timestamps make record history and auditing easier to
    # inspect without requiring every concrete model to redefine these fields.
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=utc_now,
        nullable=False,
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=utc_now,
        onupdate=utc_now,
        nullable=False,
    )

    # All future concrete models should inherit from this class to receive a
    # consistent primary key and timestamp contract.
